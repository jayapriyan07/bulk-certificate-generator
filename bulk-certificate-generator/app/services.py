from pathlib import Path
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import A4
from .models import Certificate, Job

GENERATED_DIR = Path("generated")
GENERATED_DIR.mkdir(exist_ok=True)

def generate_certificate(event_name, event_date, recipient_name, certificate_id):
    path = GENERATED_DIR / f"certificate_{certificate_id}.pdf"
    c = canvas.Canvas(str(path), pagesize=A4)
    width, height = A4
    c.setLineWidth(3)
    c.rect(35, 35, width - 70, height - 70)
    c.setFont("Helvetica-Bold", 30)
    c.drawCentredString(width/2, height-180, "CERTIFICATE OF PARTICIPATION")
    c.setFont("Helvetica", 16)
    c.drawCentredString(width/2, height-250, "This certificate is proudly presented to")
    c.setFont("Helvetica-Bold", 26)
    c.drawCentredString(width/2, height-310, recipient_name)
    c.setFont("Helvetica", 15)
    c.drawCentredString(width/2, height-370, f"for participating in {event_name}")
    c.drawCentredString(width/2, height-400, f"on {event_date}")
    c.setFont("Helvetica", 11)
    c.drawCentredString(width/2, 100, "Generated by Bulk Certificate Generator API")
    c.save()
    return str(path)
