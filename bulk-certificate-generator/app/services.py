from pathlib import Path
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors

BASE_DIR = Path(__file__).resolve().parent.parent
GENERATED_DIR = BASE_DIR / "generated"
GENERATED_DIR.mkdir(parents=True, exist_ok=True)

def _draw_fitted_centred_text(c, text: str, font_name: str, max_size: int, min_size: int, y: float, max_width: float) -> int:
    size = max_size
    while size > min_size and c.stringWidth(text, font_name, size) > max_width:
        size -= 1
    c.setFont(font_name, size)
    c.drawCentredString(A4[0] / 2, y, text)
    return size

def generate_certificate(event_name: str, event_date: str, recipient_name: str, certificate_id: int) -> str:
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    path = (GENERATED_DIR / f"certificate_{certificate_id}.pdf").resolve()
    
    c = canvas.Canvas(str(path), pagesize=A4)
    width, height = A4
    
    # Metadata
    c.setTitle(f"Certificate - {recipient_name}")
    c.setAuthor("Bulk Certificate Generator API")
    c.setSubject(event_name)

    # Margins and usable width
    usable_width = width - 100

    # Outer primary border (Deep Navy)
    c.setStrokeColor(colors.HexColor("#1A365D"))
    c.setLineWidth(3)
    c.rect(32, 32, width - 64, height - 64)

    # Inner decorative border (Soft Gold)
    c.setStrokeColor(colors.HexColor("#D69E2E"))
    c.setLineWidth(1)
    c.rect(38, 38, width - 76, height - 76)

    # Header title
    c.setFillColor(colors.HexColor("#1A365D"))
    c.setFont("Helvetica-Bold", 28)
    c.drawCentredString(width / 2, height - 170, "CERTIFICATE OF PARTICIPATION")

    # Sub-header
    c.setFillColor(colors.HexColor("#4A5568"))
    c.setFont("Helvetica", 16)
    c.drawCentredString(width / 2, height - 235, "This certificate is proudly presented to")

    # Recipient Name (auto-scaled to fit within margins)
    c.setFillColor(colors.HexColor("#1A202C"))
    _draw_fitted_centred_text(c, recipient_name, "Helvetica-Bold", max_size=26, min_size=14, y=height - 295, max_width=usable_width)

    # Decorative separator line under recipient name
    c.setStrokeColor(colors.HexColor("#D69E2E"))
    c.setLineWidth(1.5)
    line_half = min(150.0, usable_width / 3)
    c.line(width / 2 - line_half, height - 315, width / 2 + line_half, height - 315)

    # Participation and Event Text
    c.setFillColor(colors.HexColor("#2D3748"))
    _draw_fitted_centred_text(c, f"for participating in {event_name}", "Helvetica", max_size=15, min_size=11, y=height - 365, max_width=usable_width)

    c.setFont("Helvetica", 14)
    c.drawCentredString(width / 2, height - 395, f"on {event_date}")

    # Footer note
    c.setFillColor(colors.HexColor("#718096"))
    c.setFont("Helvetica", 10)
    c.drawCentredString(width / 2, 85, f"Certificate ID: {certificate_id}  |  Generated by Bulk Certificate Generator API")

    c.save()
    return str(path)

